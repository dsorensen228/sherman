#!/usr/bin/env python3
"""Create a dimensioned assembly view and enclosure-fit SCAD from the saved PCB.

The native KiCad 3D render is separate; these solids use manufacturer envelopes.
Run using the PCB-local verification environment.
"""

from pathlib import Path

import cairosvg
import verify as v

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
_, pads, _, mounts = v.read_board(HERE / "charging-interlock-rev-b.kicad_pcb")
errors, gaps, shapes = v.mechanical_errors(pads, mounts)
assert not errors, errors
svg = [
    '<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="900" viewBox="-4 -5 46.1 34.575">',
    '<rect x="-4" y="-5" width="46.1" height="34.575" fill="#faf8f1"/>',
    "<style>text{font-family:Arial,sans-serif;text-anchor:middle;fill:#132b35}</style>",
    '<text x="19.05" y="-3.3" font-size="1.15" font-weight="bold">SHERMAN · REV B · COMPONENT SIDE</text>',
    '<text x="19.05" y="-1.5" font-size=".85">38.10 × 24.13 mm — original outline and mounting holes</text>',
    '<rect width="38.1" height="24.13" rx=".15" fill="#dde9dd" stroke="#253d3b" stroke-width=".12"/>',
]
for ref, shape in shapes.items():
    parts = list(shape.geoms) if hasattr(shape, "geoms") else [shape]
    for p in parts:
        points = " ".join(f"{x:.4f},{y:.4f}" for x, y in p.exterior.coords)
        svg.append(
            f'<polygon points="{points}" fill="{"#a9b6bc" if ref.startswith("H") else "#fffdf6"}" stroke="#536873" stroke-width=".08"/>'
        )
    if not ref.startswith("H"):
        x, y = shape.centroid.coords[0]
        if ref in ("R1", "R4", "R5", "R6"):
            x = 0.85
        overrides = {
            "R2": (33.85, 17.78),
            "R3": (35.56, 18.8),
            "R7": (29.464, 3.5),
            "J1": (12.192, 19.1),
            "J2": (23.622, 20.3),
            "J3": (20.32, 5.3),
            "Q1": (31.24, 8.0),
            "C1": (11.41, 1.65),
        }
        x, y = overrides.get(ref, (x, y))
        label = ref if ref != "U1" else "U1 · SOCKET + IC"
        svg.append(f'<text x="{x}" y="{y + 0.18}" font-size=".65">{label}</text>')
for (ref, n), p in pads.items():
    x, y = p["x"], p["y"]
    r = p["drill"] / 2
    if n == "1":
        svg.append(
            f'<rect x="{x - r - 0.14}" y="{y - r - 0.14}" width="{2 * r + 0.28}" height="{2 * r + 0.28}" fill="#c08b2a"/>'
        )
    else:
        svg.append(f'<circle cx="{x}" cy="{y}" r="{r + 0.14}" fill="#c08b2a"/>')
    svg.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="#faf8f1"/>')
    if ref == "U1":
        svg.append(
            f'<text x="{x}" y="{y + (0.97 if int(n) <= 7 else -0.72)}" font-size=".58">{n}</text>'
        )
for x, y, d in mounts:
    svg.append(
        f'<circle cx="{x}" cy="{y}" r="{d / 2}" fill="#faf8f1" stroke="#536873" stroke-width=".08"/>'
    )
svg += [
    '<path d="M8.75 10.3 Q10.1 11.18 8.75 12.05" fill="none" stroke="#132b35" stroke-width=".16"/>',
    '<text x="30.988" y="8.95" font-size=".6">C</text>',
    '<text x="30.988" y="16.45" font-size=".6">E</text>',
    '<text x="34.45" y="11.5" font-size=".57">flat →</text>',
    '<text x="19.05" y="26.05" font-size=".75">Maximum body envelopes · minimum gap 0.702 mm</text>',
    '<text x="19.05" y="27.45" font-size=".7">Pin 1 lower-left; notch left. Q1 flat right; emitter at bottom.</text>',
    '<text x="19.05" y="28.7" font-size=".62">Gray circles reserve Ø4.40 mm mounting hardware; use assembly instructions for lead forming.</text>',
    "</svg>",
]
(HERE / "assembly.svg").write_text("\n".join(svg) + "\n")
cairosvg.svg2png(url=str(HERE / "assembly.svg"), write_to=str(HERE / "assembly.png"))
# Fit model Z=0 is PCB underside. Deliberately excludes underside solder and harness plugs.
scad = [
    "// Generated by electronics/pcb/charging-interlock-rev-b/render-assembly.py.",
    "// Manufacturer maximum body envelopes; see manufacturer-checks.md. Units mm.",
    "$fn=48;",
    "union() {",
    "difference() { cube([38.1,24.13,1.6]);",
]
for x, y, d in mounts:
    scad.append(f"translate([{x},{y},-.1]) cylinder(d={d},h=1.8);")
scad.append("}")


def cube(x, y, z, w, d, h):
    scad.append(
        f"translate([{x:.6f},{y:.6f},{z:.6f}]) cube([{w:.6f},{d:.6f},{h:.6f}]);"
    )


# One conservative closed solid per body joined to board via actual lead locations.
for ref, shape in shapes.items():
    if ref.startswith("H"):
        continue
    if ref == "U1":
        cube(17.78 - 8.99, 11.176 - 5.1, 1.6, 17.98, 10.2, 5.1)
        cube(17.78 - 9.845, 11.176 - 3.3, 6.7, 19.69, 6.6, 5.08)
    elif ref.startswith("R"):
        p = pads[ref, "1"]
        scad.append(f"translate([{p['x']},{p['y']},2.8]) cylinder(d=2.6,h=6.8);")
    else:
        x, y, xx, yy = shape.bounds
        z, h = (
            (5.1, 5.33) if ref == "Q1" else (2.8, 3.14) if ref == "C1" else (1.6, 2.54)
        )
        cube(x, y, z, xx - x, yy - y, h)
    for (r, n), p in pads.items():
        if r != ref:
            continue
        height = (
            8.4
            if ref.startswith("J")
            else 8.1
            if ref.startswith("R")
            else 3.6
            if ref == "Q1"
            else 1.3
            if ref == "C1"
            else 0.3
        )
        scad.append(f"translate([{p['x']},{p['y']},1.5]) cylinder(d=.6,h={height});")
scad.append("}")
source = (
    ROOT / "models/components/source/sherman-charging-interlock-rev-b-envelope.scad"
)
source.write_text("\n".join(scad) + "\n")
print("Created assembly.svg/png and Rev B SCAD, envelope 38.10 × 24.13 × 11.78 mm.")
